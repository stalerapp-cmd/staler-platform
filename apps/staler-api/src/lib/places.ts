/** Loose comparison key for place names. */
export const placeKey = (v: string) =>
  v.trim().toLowerCase().replace(/[أإآ]/g, 'ا').replace(/ة/g, 'ه').replace(/ى/g, 'ي').replace(/\s+/g, ' ');

/** Every town name, once, for the city field's suggestions. */
export const ALL_TOWNS = [...new Set(GOVERNORATES.flatMap((g) => g.towns))];

/** The governorate a typed city belongs to (if we know it). */
export function governorateOf(city: string | null | undefined): Governorate | null {
  if (!city) return null;
  const k = placeKey(city);
  return GOVERNORATES.find((g) => placeKey(g.ar) === k || placeKey(g.en) === k || g.towns.some((t) => placeKey(t) === k)) ?? null;
}

/** A selection (governorate ids and single towns) as the list of names the server should match. */
export function expandPlaces(sel: string[]): string[] {
  const out = new Set<string>();
  for (const s of sel) {
    const g = GOVERNORATES.find((x) => `gov:${x.id}` === s);
    if (g) {
      out.add(g.ar);
      out.add(g.en);
      g.towns.forEach((t) => out.add(t));
    } else if (s.startsWith('town:')) out.add(s.slice(5));
  }
  return [...out];
}
