export function serverTextAr(message?: string | null): string | null {
  if (!message) return null;
  if (AR[message]) return AR[message]!;
  for (const [re, ar] of PATTERNS) {
    const m = message.match(re);
    if (m) return ar(m);
  }
  return null;
}

/** English fallback: makes the schema library's generic messages readable. */
export function serverTextEn(message?: string | null): string | null {
  if (!message) return null;
  if (EN[message]) return EN[message]!;
  for (const [re, , en] of PATTERNS) {
    const m = message.match(re);
    if (m) return en(m);
  }
  return null;
}

/** True when an English server message has no Arabic yet (used by the test-suite). */
export const hasArabic = (message: string) => serverTextAr(message) !== null;
